
SELECT SDO_NET.VALIDATE_NETWORK(
               'CITY_NETWORK', 'TRUE'
       ) AS VALID_NETWORK
FROM DUAL;

SELECT COUNT(*) AS NODE_COUNT
FROM CITY_NETWORK_NODE$;

SELECT COUNT(*) AS LINK_COUNT
FROM CITY_NETWORK_LINK$;

SELECT NODE_ID, NODE_NAME
FROM CITY_NETWORK_NODE$
ORDER BY NODE_ID;

SELECT LINK_ID, START_NODE_ID,
       END_NODE_ID, COST
FROM CITY_NETWORK_LINK$
ORDER BY LINK_ID;
